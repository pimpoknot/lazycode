#!/usr/bin/env python3
"""Regenerates runtime/versions.lock from the latest upstream releases.

Each line is: tool version os arch sha256 url
The checksums come from GitHub release digests and from Node's SHASUMS256.txt.
"""
import json
import os
import sys
import urllib.request

PLATFORMS = [("linux", "x86_64"), ("linux", "arm64"), ("macos", "x86_64"), ("macos", "arm64")]

ASSETS = {
    "nvim": ("neovim/neovim", {
        ("linux", "x86_64"): "nvim-linux-x86_64.tar.gz",
        ("linux", "arm64"): "nvim-linux-arm64.tar.gz",
        ("macos", "x86_64"): "nvim-macos-x86_64.tar.gz",
        ("macos", "arm64"): "nvim-macos-arm64.tar.gz",
    }),
    # Icons for the window when the main font has none. Same file on every platform.
    "fonts": ("ryanoasis/nerd-fonts", {platform: "NerdFontsSymbolsOnly.tar.xz" for platform in PLATFORMS}),
    "lazygit": ("jesseduffield/lazygit", {
        ("linux", "x86_64"): "lazygit_{v}_linux_x86_64.tar.gz",
        ("linux", "arm64"): "lazygit_{v}_linux_arm64.tar.gz",
        ("macos", "x86_64"): "lazygit_{v}_darwin_x86_64.tar.gz",
        ("macos", "arm64"): "lazygit_{v}_darwin_arm64.tar.gz",
    }),
    "ripgrep": ("BurntSushi/ripgrep", {
        ("linux", "x86_64"): "ripgrep-{v}-x86_64-unknown-linux-musl.tar.gz",
        ("linux", "arm64"): "ripgrep-{v}-aarch64-unknown-linux-musl.tar.gz",
        ("macos", "x86_64"): "ripgrep-{v}-x86_64-apple-darwin.tar.gz",
        ("macos", "arm64"): "ripgrep-{v}-aarch64-apple-darwin.tar.gz",
    }),
    "fd": ("sharkdp/fd", {
        ("linux", "x86_64"): "fd-v{v}-x86_64-unknown-linux-musl.tar.gz",
        ("linux", "arm64"): "fd-v{v}-aarch64-unknown-linux-musl.tar.gz",
        ("macos", "x86_64"): "fd-v{v}-x86_64-apple-darwin.tar.gz",
        ("macos", "arm64"): "fd-v{v}-aarch64-apple-darwin.tar.gz",
    }),
}

# Held back until the end-to-end suites pass on a newer release.
PINNED = {"nvim": "v0.12.4"}

NODE_NAMES = {
    ("linux", "x86_64"): "linux-x64",
    ("linux", "arm64"): "linux-arm64",
    ("macos", "x86_64"): "darwin-x64",
    ("macos", "arm64"): "darwin-arm64",
}


def fetch(url):
    headers = {"User-Agent": "lazycode-update-versions", "Accept": "application/vnd.github+json"}
    token = os.environ.get("GITHUB_TOKEN")
    if token and "api.github.com" in url:
        headers["Authorization"] = "Bearer " + token
    with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=30) as response:
        return response.read()


def github_rows():
    rows = []
    for tool, (repo, names) in ASSETS.items():
        path = f"tags/{PINNED[tool]}" if tool in PINNED else "latest"
        release = json.loads(fetch(f"https://api.github.com/repos/{repo}/releases/{path}"))
        version = release["tag_name"].lstrip("v")
        assets = {asset["name"]: asset for asset in release["assets"]}
        for platform in PLATFORMS:
            name = names[platform].format(v=version)
            asset = assets[name]
            digest = asset.get("digest") or ""
            if not digest.startswith("sha256:"):
                sys.exit(f"{tool}: no sha256 digest for {name}")
            rows.append((tool, version, *platform, digest.split(":", 1)[1], asset["browser_download_url"]))
    return rows


def node_rows():
    releases = json.loads(fetch("https://nodejs.org/dist/index.json"))
    version = next(item["version"] for item in releases if item["lts"])
    sums = {}
    for line in fetch(f"https://nodejs.org/dist/{version}/SHASUMS256.txt").decode().splitlines():
        digest, name = line.split()
        sums[name] = digest
    rows = []
    for platform in PLATFORMS:
        name = f"node-{version}-{NODE_NAMES[platform]}.tar.gz"
        rows.append(("node", version.lstrip("v"), *platform, sums[name], f"https://nodejs.org/dist/{version}/{name}"))
    return rows


def main():
    rows = sorted(github_rows() + node_rows())
    target = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "runtime", "versions.lock")
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf8") as out:
        out.write("# tool version os arch sha256 url (generated by scripts/update-versions.py)\n")
        for row in rows:
            out.write(" ".join(row) + "\n")
    print(f"{len(rows)} entries written to {target}")


if __name__ == "__main__":
    main()
